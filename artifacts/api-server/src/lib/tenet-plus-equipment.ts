function mergeCategories(...groups: QuoteOptionCategory[][]): QuoteOptionCategory[] {
  const merged = new Map<string, string[]>();
  for (const group of groups) {
    for (const entry of group) {
      const items = merged.get(entry.category) ?? [];
      for (const item of entry.items) {
        if (!items.includes(item)) items.push(item);
      }
      merged.set(entry.category, items);
    }
  }
  return Array.from(merged, ([category, items]) => ({ category, items }));
}

function normalize(value: string): string {
  return value.trim().toLowerCase().replace(/ё/g, "е");
}

export function getTenetPlusOptions(model: string, complectation: string): QuoteOptionCategory[] {
  const modelName = normalize(model);
  const trimName = normalize(complectation);

  if (modelName.includes("l4")) {
    if (trimName.includes("элегант")) {
      return mergeCategories(L4_STYLE, L4_ELEGANT_ADDITIONS);
    }
    return L4_STYLE;
  }

  if (modelName.includes("l6")) {
    if (trimName.includes("ультра")) {
      return mergeCategories(L6_ELEGANT, L6_ULTRA_ADDITIONS);
    }
    return L6_ELEGANT;
  }

  return [];
}